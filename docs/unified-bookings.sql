-- Flujo único de reservas: cambios para bases con ddl-auto=none.
-- Con ddl-auto=update la tabla la crea Hibernate y el CHECK lo amplía BookingStatusSchemaMigration.

ALTER TABLE event_bookings DROP CONSTRAINT IF EXISTS event_bookings_status_check;
ALTER TABLE event_bookings ADD CONSTRAINT event_bookings_status_check CHECK (status IN
    ('PENDIENTE', 'ACEPTADA', 'CONFIRMADA', 'CANCELADA', 'LISTA_ESPERA', 'COMPLETADA', 'NO_ASISTIO'));

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    type VARCHAR(40) NOT NULL,
    title VARCHAR(120) NOT NULL,
    message VARCHAR(255) NOT NULL,
    event_title VARCHAR(180),
    booking_code VARCHAR(30),
    action_label VARCHAR(40),
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON notifications (user_id, created_at);

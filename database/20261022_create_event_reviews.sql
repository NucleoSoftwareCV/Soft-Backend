-- Ejecutar sobre la base de OONA si Hibernate no administra el esquema.
-- En dev, ddl-auto=update crea esta tabla desde EventReview automáticamente.
-- Este proyecto no incluye Flyway: el script no se ejecuta por su nombre.
BEGIN;
CREATE TABLE IF NOT EXISTS event_reviews (
                                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             event_id BIGINT NOT NULL,
                                             user_id BIGINT NOT NULL,
                                             stars INTEGER NOT NULL,
                                             comment VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
                             CONSTRAINT fk_event_reviews_event FOREIGN KEY (event_id) REFERENCES events(id),
    CONSTRAINT fk_event_reviews_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT uk_event_reviews_event_user UNIQUE (event_id, user_id),
    CONSTRAINT ck_event_reviews_stars CHECK (stars BETWEEN 1 AND 5)
    );
CREATE INDEX IF NOT EXISTS idx_event_reviews_event_created
    ON event_reviews (event_id, created_at, id);
COMMIT;

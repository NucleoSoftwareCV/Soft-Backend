-- Ejecutar antes de desplegar, en el esquema de Oona y tras el SQL de Support.
-- Reutiliza las tablas de Franz y Sleyter. No inserta movimientos ni saldos.
BEGIN;

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    type VARCHAR(40) NOT NULL,
    title VARCHAR(120) NOT NULL,
    message VARCHAR(255) NOT NULL,
    event_title VARCHAR(180),
    booking_code VARCHAR(30),
    action_label VARCHAR(40),
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL
    );

CREATE INDEX IF NOT EXISTS idx_notifications_user_created
    ON notifications(user_id, created_at);

-- Si Hibernate creó una restricción de tipos en un despliegue anterior,
-- conserva sus valores permitidos y añade los dos propios de Support.
DO $$
DECLARE old_check TEXT;
BEGIN
SELECT pg_get_expr(conbin, conrelid) INTO old_check
FROM pg_constraint
WHERE conrelid = 'notifications'::regclass
      AND conname = 'notifications_type_check'
      AND contype = 'c';

IF old_check IS NOT NULL AND (
        position('REEMBOLSO_APROBADO' IN old_check) = 0 OR
        position('REEMBOLSO_RECHAZADO' IN old_check) = 0
    ) THEN
ALTER TABLE notifications DROP CONSTRAINT notifications_type_check;
EXECUTE format(
        'ALTER TABLE notifications ADD CONSTRAINT notifications_type_check CHECK ((%s) OR type IN (%L, %L))',
        old_check, 'REEMBOLSO_APROBADO', 'REEMBOLSO_RECHAZADO'
        );
END IF;
END $$;

CREATE TABLE IF NOT EXISTS user_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    available_points INTEGER NOT NULL,
    status VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP NOT NULL
    );

CREATE TABLE IF NOT EXISTS earn_points_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reward INTEGER NOT NULL,
    description VARCHAR(255),
    active BOOLEAN NOT NULL,
    experience_type_id BIGINT NOT NULL REFERENCES experience_types(id)
    );

CREATE TABLE IF NOT EXISTS points_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_points_id BIGINT NOT NULL REFERENCES user_points(id),
    event_attendee_id BIGINT REFERENCES event_attendees(id),
    event_id BIGINT REFERENCES events(id),
    points_rules_id BIGINT NOT NULL REFERENCES earn_points_rules(id),
    type VARCHAR(255) NOT NULL,
    points_quantity INTEGER NOT NULL,
    balance_after INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL
    );

CREATE INDEX IF NOT EXISTS idx_user_points_support_user ON user_points(user_id);
CREATE INDEX IF NOT EXISTS idx_points_transactions_support_history
    ON points_transactions(user_points_id, created_at DESC, id DESC);

COMMIT;

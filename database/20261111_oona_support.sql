-- ============================================================
-- OONA SUPPORT — CREACIÓN COMPLETA
-- Motor: PostgreSQL
--
-- Requiere las tablas existentes:
-- users, roles, event_bookings, session_bookings, events, payments.
--
-- No elimina registros ni recrea tablas existentes.
-- ============================================================

BEGIN;

-- ============================================================
-- 1. La gestión de soporte utiliza el rol administrador existente.

-- ============================================================
-- 2. TICKETS DE SOPORTE
-- Incluye reservas de eventos y sesiones individuales.
-- ============================================================

CREATE TABLE IF NOT EXISTS support_tickets (
                                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                               ticket_number VARCHAR(30) NOT NULL UNIQUE,
    complaint_reference VARCHAR(100),

    user_id BIGINT NOT NULL
    REFERENCES users(id),

    assigned_admin_id BIGINT
    REFERENCES users(id),

    category VARCHAR(40) NOT NULL
    CHECK (
              category IN (
              'PAGOS',
              'REEMBOLSOS',
              'RESERVAS',
              'EVENTOS',
              'REWARDS',
              'CANJES',
              'CUENTA',
              'PROFESIONALES',
              'TECNICO',
              'OTROS'
                          )
    ),

    subject VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,

    priority VARCHAR(20) NOT NULL DEFAULT 'MEDIA'
    CHECK (
              priority IN (
              'BAJA',
              'MEDIA',
              'ALTA',
              'CRITICA'
                          )
    ),

    status VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE'
    CHECK (
              status IN (
              'PENDIENTE',
              'ASIGNADO',
              'EN_REVISION',
              'ESPERANDO_USUARIO',
              'RESUELTO',
              'CERRADO',
              'REABIERTO'
                        )
    ),

    booking_id BIGINT
    REFERENCES event_bookings(id),

    session_booking_id BIGINT
    REFERENCES session_bookings(id),

    event_id BIGINT
    REFERENCES events(id),

    payment_id BIGINT
    REFERENCES payments(id),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

-- ============================================================
-- 3. RESPUESTAS PÚBLICAS Y NOTAS INTERNAS
-- ============================================================

CREATE TABLE IF NOT EXISTS support_responses (
                                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                                 ticket_id BIGINT NOT NULL
                                                 REFERENCES support_tickets(id),

    sender_id BIGINT NOT NULL
    REFERENCES users(id),

    message TEXT NOT NULL,
    is_internal BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

-- ============================================================
-- 4. EVIDENCIAS Y ARCHIVOS ADJUNTOS
-- Los archivos físicos se guardan en almacenamiento privado.
-- ============================================================

CREATE TABLE IF NOT EXISTS support_attachments (
                                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                                   ticket_id BIGINT NOT NULL
                                                   REFERENCES support_tickets(id),

    response_id BIGINT
    REFERENCES support_responses(id),

    file_name VARCHAR(255) NOT NULL,
    file_path VARCHAR(500) NOT NULL,
    content_type VARCHAR(100) NOT NULL,

    uploaded_by BIGINT NOT NULL
    REFERENCES users(id),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

-- ============================================================
-- 5. SOLICITUDES DE REEMBOLSO
-- transaction_id referencia un pago existente.
-- ============================================================

CREATE TABLE IF NOT EXISTS refund_requests (
                                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                               ticket_id BIGINT NOT NULL UNIQUE
                                               REFERENCES support_tickets(id),

    transaction_id BIGINT NOT NULL
    REFERENCES payments(id),

    requested_amount NUMERIC(10, 2) NOT NULL
    CHECK (requested_amount > 0),

    approved_amount NUMERIC(10, 2)
    CHECK (
              approved_amount > 0
              AND approved_amount <= requested_amount
          ),

    reason VARCHAR(100) NOT NULL,
    admin_observation TEXT,

    status VARCHAR(30) NOT NULL DEFAULT 'SOLICITADO'
    CHECK (
              status IN (
              'SOLICITADO',
              'EN_EVALUACION',
              'APROBADO',
              'RECHAZADO',
              'EN_PROCESAMIENTO',
              'PROCESADO',
              'ERROR'
                        )
    ),

    provider_refund_id VARCHAR(150) UNIQUE,
    idempotency_key VARCHAR(80) NOT NULL UNIQUE,

    processed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (
              status NOT IN (
              'APROBADO',
              'EN_PROCESAMIENTO',
              'PROCESADO',
              'ERROR'
                            )
    OR approved_amount IS NOT NULL
    ),

    CHECK (
              status <> 'PROCESADO'
              OR (
              provider_refund_id IS NOT NULL
              AND processed_at IS NOT NULL
                 )
    )
    );

-- ============================================================
-- 6. AUDITORÍA E HISTORIAL
-- ============================================================

CREATE TABLE IF NOT EXISTS support_audit (
                                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                             ticket_id BIGINT
                                             REFERENCES support_tickets(id),

    actor_id BIGINT NOT NULL
    REFERENCES users(id),

    action VARCHAR(80) NOT NULL,
    detail VARCHAR(2000) NOT NULL,

    internal BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

-- ============================================================
-- 7. ÍNDICES
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_support_user
    ON support_tickets(user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_support_queue
    ON support_tickets(status, category, priority, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_support_assignee
    ON support_tickets(assigned_admin_id);

CREATE INDEX IF NOT EXISTS idx_support_session_booking
    ON support_tickets(session_booking_id);

CREATE INDEX IF NOT EXISTS idx_support_responses
    ON support_responses(ticket_id, created_at, id);

CREATE INDEX IF NOT EXISTS idx_support_attachments
    ON support_attachments(ticket_id);

CREATE INDEX IF NOT EXISTS idx_support_audit
    ON support_audit(ticket_id, created_at, id);

CREATE INDEX IF NOT EXISTS idx_refund_payment
    ON refund_requests(transaction_id, status);

-- ============================================================
-- 8. RETIRAR ACCESO OPERATIVO LEGADO
-- Se conservan los registros históricos de agentes y asignaciones.
-- El código ya no concede permisos de soporte mediante ROLE_SUPPORT.

COMMIT;
